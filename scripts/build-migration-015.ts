/**
 * Generates database/migrations/015_province_borders.sql from
 * database/seed/turkey_province_borders.geojson.
 *
 *   npx ts-node scripts/build-migration-015.ts           # write the file
 *   npx ts-node scripts/build-migration-015.ts --check   # exit 1 if stale
 *
 * The boundary file is shared byte-for-byte with the app
 * (firewatch-tr/assets/data/il_sinirlari.geojson); both repos pin its
 * SHA-256. Its source is geoBoundaries gbOpen TUR ADM1 (TUR-ADM1-25984515),
 * derived from OpenStreetMap — © OpenStreetMap contributors, ODbL 1.0.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

export const BORDERS_PATH = path.join(__dirname, '..', 'database', 'seed', 'turkey_province_borders.geojson');
export const MIGRATION_PATH = path.join(__dirname, '..', 'database', 'migrations', '015_province_borders.sql');
export const BORDERS_SHA256 = 'd51cf911a4cf6582142b3c81eb2594e828b08c600d63054a317c1281d283002a';
export const BORDERS_SOURCE =
  'geoBoundaries gbOpen TUR ADM1 (TUR-ADM1-25984515), derived from OpenStreetMap; © OpenStreetMap contributors, ODbL 1.0';

interface Feature {
  properties: { plaka: string; il: string };
  geometry: { type: 'Polygon' | 'MultiPolygon'; coordinates: unknown };
}

export function loadBorders(): { bytes: Buffer; features: Feature[] } {
  const bytes = fs.readFileSync(BORDERS_PATH);
  const sha = crypto.createHash('sha256').update(bytes).digest('hex');
  if (sha !== BORDERS_SHA256) {
    throw new Error(`turkey_province_borders.geojson SHA-256 ${sha} != pinned ${BORDERS_SHA256}`);
  }
  const features = (JSON.parse(bytes.toString('utf8')).features ?? []) as Feature[];
  const plates = features.map((f) => Number(f.properties.plaka));
  if (features.length !== 81 || new Set(plates).size !== 81 || plates.some((p, i) => p !== i + 1)) {
    throw new Error('expected 81 provinces with plates 01..81 in order');
  }
  return { bytes, features };
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function buildMigration(): string {
  const { features } = loadBorders();
  const rows = features
    .map((f) => `  (${Number(f.properties.plaka)}, ${q(f.properties.il)}, ${q(JSON.stringify(f.geometry))})`)
    .join(',\n');

  return `-- Migration 015 — province boundaries; one province function for everything
--
-- GENERATED by scripts/build-migration-015.ts from
-- database/seed/turkey_province_borders.geojson (sha256 ${BORDERS_SHA256}).
-- Do not edit by hand; edit the generator and re-run it.
--
-- Until now every "which province is this point in" question was answered
-- with the nearest province CENTRE (turkey_cities holds one point per
-- province), so points near a border landed in the neighbour: on
-- 2026-11-07 a quarter of all fire incidents had the wrong province
-- (e.g. "Diyarbakır / Siverek"). This migration adds the 81 real province
-- polygons and province_for_point(), which every caller now uses.
--
-- Boundaries: ${BORDERS_SOURCE}.
--
-- ADDITIVE except one row: turkey_cities id 33 is renamed from its former
-- official name "İçel" to "Mersin" (the app already shows Mersin; old-name
-- lookups keep working through the aliases in code). Existing incident and
-- detection rows are NOT changed here — scripts/backfill-provinces-015.ts
-- does that after the code that uses this migration is deployed, logging
-- every old value in province_reassign_015 so it can be undone.
--
-- PRE-FLIGHT — expect NULL, NULL and 'İçel':
--   SELECT to_regclass('public.turkey_province_borders'),
--          to_regprocedure('province_for_point(geometry)'),
--          (SELECT name FROM turkey_cities WHERE id = 33);
--
-- Take a Neon backup branch before applying to production.

BEGIN;

CREATE TABLE turkey_province_borders (
  province_id INTEGER PRIMARY KEY REFERENCES turkey_cities(id),
  name        TEXT NOT NULL,
  geom        geometry(MultiPolygon, 4326) NOT NULL,
  source      TEXT NOT NULL
);

INSERT INTO turkey_province_borders (province_id, name, geom, source)
SELECT v.id, v.name, ST_Multi(ST_MakeValid(ST_SetSRID(ST_GeomFromGeoJSON(v.geojson), 4326))), ${q(BORDERS_SOURCE)}
FROM (VALUES
${rows}
) AS v(id, name, geojson);

CREATE INDEX turkey_province_borders_geom_idx ON turkey_province_borders USING GIST (geom);

-- The province a point is in. Inside a polygon: that province (on a shared
-- border, the one the point is deeper inside; ties to the lower id). At sea
-- or just outside the simplified outline: the nearest province.
CREATE FUNCTION province_for_point(p geometry) RETURNS INTEGER
LANGUAGE sql STABLE PARALLEL SAFE AS $fn$
  SELECT COALESCE(
    (SELECT b.province_id
       FROM turkey_province_borders b
      WHERE ST_Intersects(b.geom, p)
      ORDER BY ST_Distance(ST_Boundary(b.geom), p) DESC, b.province_id
      LIMIT 1),
    (SELECT b.province_id
       FROM turkey_province_borders b
      ORDER BY b.geom <-> p, b.province_id
      LIMIT 1)
  )
$fn$;

-- The region key a province belongs to, in the vocabulary of region_key
-- columns ('ic_anadolu', 'guneydogu_anadolu', ...). Same folding as
-- src/utils/regions.ts; on 2026-11-07 it reproduced every stored
-- fire_incidents.region_key from its city_id.
CREATE FUNCTION province_region_key(province INTEGER) RETURNS TEXT
LANGUAGE sql STABLE PARALLEL SAFE AS $fn$
  SELECT replace(
           regexp_replace(lower(translate(region, 'İIıÇçĞğÖöŞşÜü', 'iiiccggoossuu')), '\\s+', ' ', 'g'),
           ' ', '_')
    FROM turkey_cities WHERE id = province
$fn$;

UPDATE turkey_cities SET name = 'Mersin' WHERE id = 33 AND name IN ('İçel', 'Icel');

-- Old values of every row the backfill changes, for an exact undo.
CREATE TABLE province_reassign_015 (
  table_name     TEXT    NOT NULL,
  row_id         BIGINT  NOT NULL,
  old_city_id    INTEGER,
  old_region_key TEXT,
  new_city_id    INTEGER,
  new_region_key TEXT,
  changed_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (table_name, row_id)
);

COMMIT;
`;
}

if (require.main === module) {
  const sql = buildMigration();
  if (process.argv.includes('--check')) {
    // CRLF-tolerant: a Windows checkout (core.autocrlf) rewrites line ends.
    const current = fs.existsSync(MIGRATION_PATH)
      ? fs.readFileSync(MIGRATION_PATH, 'utf8').replace(/\r\n/g, '\n')
      : '';
    if (current !== sql) {
      console.error('015_province_borders.sql is stale: run scripts/build-migration-015.ts');
      process.exit(1);
    }
    console.log('015_province_borders.sql is up to date');
  } else {
    fs.writeFileSync(MIGRATION_PATH, sql);
    console.log(`wrote ${MIGRATION_PATH} (${sql.length} bytes)`);
  }
}
